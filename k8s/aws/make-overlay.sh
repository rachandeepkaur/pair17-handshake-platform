#!/usr/bin/env bash
# Generate k8s/overlays/aws (git-ignored: it contains the account id) for EKS.
#
#   AWS_REGION=us-east-1 VERSION=1.0.0 [OLLAMA_HOST=http://10.0.1.23:11434] k8s/aws/make-overlay.sh
#
# On top of k8s/base it:
#  - points every image at ECR with the version tag
#  - makes p17-uploads ReadWriteOnce (EBS cannot be shared across nodes) and runs the
#    three services that mount it as 1 replica, so they never need it on two nodes
#  - optionally points the assistant and memory worker at an Ollama server you run
set -euo pipefail
cd "$(dirname "$0")/../.."

AWS_REGION=${AWS_REGION:-$(aws configure get region 2>/dev/null || true)}
: "${AWS_REGION:?set AWS_REGION, e.g. export AWS_REGION=us-east-1}"
export AWS_REGION
VERSION=${VERSION:-1.0.0}
ACCOUNT_ID=${ACCOUNT_ID:-$(aws sts get-caller-identity --query Account --output text)}
ECR="${ACCOUNT_ID}.dkr.ecr.${AWS_REGION}.amazonaws.com"
OUT=k8s/overlays/aws
mkdir -p "$OUT"

{
  echo "# Generated by k8s/aws/make-overlay.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Do not edit by hand."
  echo "apiVersion: kustomize.config.k8s.io/v1beta1"
  echo "kind: Kustomization"
  echo "resources: [../../base]"
  echo "images:"
  for img in p17-student-service p17-company-service p17-job-service p17-application-service p17-event-service \
             p17-assistant-service p17-frontend p17-kafka-worker; do
    echo "  - {name: ${img}, newName: ${ECR}/${img}, newTag: \"${VERSION}\"}"
  done
  echo "patches:"
  echo "  - target: {kind: PersistentVolumeClaim, name: p17-uploads}"
  echo "    patch: '[{\"op\": \"replace\", \"path\": \"/spec/accessModes\", \"value\": [\"ReadWriteOnce\"]}]'"
  for svc in student company application; do
    echo "  - target: {kind: Deployment, name: p17-${svc}-service}"
    echo "    patch: '[{\"op\": \"replace\", \"path\": \"/spec/replicas\", \"value\": 1}]'"
    echo "  - target: {kind: HorizontalPodAutoscaler, name: p17-${svc}-service}"
    echo "    patch: '[{\"op\": \"replace\", \"path\": \"/spec/minReplicas\", \"value\": 1}, {\"op\": \"replace\", \"path\": \"/spec/maxReplicas\", \"value\": 1}]'"
  done
  if [[ -n ${OLLAMA_HOST:-} ]]; then
    echo "  - target: {kind: ConfigMap, name: p17-assistant-config}"
    echo "    patch: '[{\"op\": \"replace\", \"path\": \"/data/OLLAMA_HOST\", \"value\": \"${OLLAMA_HOST}\"}]'"
  fi
} > "$OUT/kustomization.yaml"

echo "SEED_IMAGE=${ECR}/p17-db-seed:${VERSION}" > "$OUT/seed-image.env"
kubectl kustomize "$OUT" > /dev/null
echo "Wrote $OUT (images: ${ECR}/*:${VERSION}${OLLAMA_HOST:+, OLLAMA_HOST=${OLLAMA_HOST}})"
